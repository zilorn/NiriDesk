#!/bin/sh
set -eu

if [ -f .env ]; then
  echo ".env already exists; refusing to overwrite it." >&2
  exit 1
fi

uid=$(id -u)
gid=$(id -g)
runtime_dir=${XDG_RUNTIME_DIR:-/run/user/$uid}
wayland_display=${WAYLAND_DISPLAY:-}

if [ -z "$wayland_display" ]; then
  for socket in "$runtime_dir"/wayland-*; do
    [ -S "$socket" ] || continue
    wayland_display=$(basename "$socket")
    break
  done
fi

if [ -z "$wayland_display" ]; then
  echo "Could not detect WAYLAND_DISPLAY. Run this script from a niri/Wayland session, or edit .env manually." >&2
  exit 1
fi

if ! command -v openssl >/dev/null 2>&1; then
  echo "openssl is required to generate .env secrets." >&2
  exit 1
fi

password=$(openssl rand -hex 12)
secret=$(openssl rand -hex 32)

umask 077
cat > .env <<EOF
# Generated by scripts/init-env.sh on $(date -Iseconds).
PUID=$uid
PGID=$gid
BIND_ADDR=0.0.0.0
PORT=8080
XDG_RUNTIME_DIR=$runtime_dir
WAYLAND_DISPLAY=$wayland_display

REMOTE_PASSWORD=$password
SESSION_SECRET=$secret
SESSION_TTL=12h

MAX_CLIENTS=4
WAYVNC_MAX_FPS=30
WAYVNC_OUTPUT=
WAYVNC_SHOW_CURSOR=true
WAYVNC_DISABLE_INPUT=false

AUDIO_ENABLED=true
AUDIO_BINARY=parec
AUDIO_DEVICE=@DEFAULT_MONITOR@

TRUST_PROXY=false
COOKIE_SECURE=auto
LOG_LEVEL=info

VERSION=0.1.0
COMMIT=local
EOF

chmod 600 .env
lan_ip=$(hostname -I 2>/dev/null | awk '{print $1}')
if [ -n "$lan_ip" ]; then
  open_url="http://$lan_ip:8080"
else
  open_url="http://<this-host-lan-ip>:8080"
fi

cat <<EOF

Created .env for UID $uid, display $wayland_display.

Access password: $password
Store it in your password manager. It is not printed again.

Start NiriDesk:
  docker compose up -d --build

Open:
  $open_url
EOF
